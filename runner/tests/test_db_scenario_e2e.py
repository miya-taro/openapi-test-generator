"""Real HTTP + PostgreSQL smoke test; opt in with OTG_INTEGRATION_DB_CONFIG.

The environment variable is a JSON object with psycopg2 connection arguments.
Only a uniquely named table is created and removed in the selected database.
"""
import json
import os
import subprocess
import sys
import threading
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

import psycopg2
import pytest
import yaml


REPO_ROOT = Path(__file__).resolve().parents[2]


def test_real_api_and_db_comparison(tmp_path):
    config_text = os.environ.get("OTG_INTEGRATION_DB_CONFIG")
    if not config_text:
        pytest.skip("OTG_INTEGRATION_DB_CONFIG is not set")
    db_config = json.loads(config_text)
    table = "otg_integration_" + uuid.uuid4().hex[:12]

    def execute(sql, params=(), fetch=False):
        with psycopg2.connect(**db_config) as connection:
            with connection.cursor() as cursor:
                cursor.execute(sql, params)
                return cursor.fetchall() if fetch else None

    execute(f'CREATE TABLE "{table}" (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
            'name text NOT NULL, location_id text NOT NULL)')
    execute(f'INSERT INTO "{table}" (id, name, location_id) VALUES '
            "(1, 'A', 'L1'), (2, 'B', 'L2')")
    execute(f'ALTER TABLE "{table}" ALTER COLUMN id RESTART WITH 3')

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_args):
            pass

        def respond(self, status, body):
            encoded = json.dumps(body).encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(encoded)))
            self.end_headers()
            self.wfile.write(encoded)

        def authorized(self):
            if self.headers.get("Authorization") != "Bearer integration-token":
                self.respond(401, {"error": "unauthorized"})
                return False
            return True

        def body(self):
            return json.loads(self.rfile.read(int(self.headers.get("Content-Length", "0"))) or b"{}")

        def do_GET(self):
            if not self.authorized():
                return
            rows = execute(f'SELECT id, name, location_id FROM "{table}" ORDER BY id DESC', fetch=True)
            if not rows:
                self.respond(400, {"error": "empty"})
                return
            data = [dict(zip(("id", "name", "location_id"), row, strict=True)) for row in rows]
            if self.path == "/wrong":
                data[0]["name"] = "wrong"
            self.respond(200, {"data": data})

        def do_POST(self):
            if not self.authorized():
                return
            body = self.body()
            if self.path == "/noop":
                self.respond(201, {"id": 1})
                return
            row = execute(
                f'INSERT INTO "{table}" (name, location_id) VALUES (%s, %s) RETURNING id',
                (body["name"], body["location_id"]), fetch=True,
            )
            self.respond(201, {"id": row[0][0]})

        def do_PUT(self):
            if not self.authorized():
                return
            execute(f'UPDATE "{table}" SET name = %s WHERE id = %s',
                    (self.body()["name"], int(self.path.split("/")[-1])))
            self.respond(200, {"ok": True})

        def do_PATCH(self):
            if not self.authorized():
                return
            execute(f'UPDATE "{table}" SET location_id = %s WHERE id = %s',
                    (self.body()["location_id"], int(self.path.split("/")[-1])))
            self.respond(200, {"ok": True})

        def do_DELETE(self):
            if not self.authorized():
                return
            execute(f'DELETE FROM "{table}" WHERE id = %s', (int(self.path.split("/")[-1]),))
            self.respond(200, {"ok": True})

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    spec = {"openapi": "3.1.0", "info": {"title": "DB integration", "version": "1"}, "paths": {
        "/data": {
            "get": {"operationId": "listData", "responses": {"200": {"description": "OK"}, "400": {"description": "Empty"}}},
            "post": {"operationId": "createData", "responses": {"201": {"description": "Created"}}},
        },
        "/data/{id}": {
            "put": {"operationId": "replaceData", "responses": {"200": {"description": "OK"}}},
            "patch": {"operationId": "patchData", "responses": {"200": {"description": "OK"}}},
            "delete": {"operationId": "deleteData", "responses": {"200": {"description": "OK"}}},
        },
        "/noop": {"post": {"operationId": "noopData", "responses": {"201": {"description": "Created"}}}},
        "/wrong": {"get": {"operationId": "wrongData", "responses": {"200": {"description": "OK"}}}},
    }}
    spec_path = tmp_path / "openapi.json"
    spec_path.write_text(json.dumps(spec), encoding="utf-8")
    config_path = tmp_path / "db.json"
    config_path.write_text(json.dumps({"postgres": db_config}), encoding="utf-8")

    mapping = {"table": table, "fields": {"id": "id", "name": "name", "location_id": "location_id"},
               "array_path": "data"}

    def run(scenarios, evidence_name):
        scenario_path = tmp_path / (evidence_name + ".yaml")
        scenario_path.write_text(yaml.safe_dump(
            {"scenarios": {"defaults": {"engine": "postgres"}, "list": scenarios}}, allow_unicode=True,
        ), encoding="utf-8")
        evidence_path = tmp_path / (evidence_name + ".json")
        process = subprocess.run(
            [sys.executable, str(REPO_ROOT / "runner" / "db_scenario_runner.py"),
             str(scenario_path), str(spec_path), "--base-url", f"http://127.0.0.1:{server.server_port}",
             "--config", str(config_path), "--skip-health-check", "--evidence-output", str(evidence_path)],
            env={**os.environ, "TEST_AUTH_TOKEN": "integration-token"},
            capture_output=True, text=True, timeout=30,
        )
        assert evidence_path.is_file(), process.stdout + process.stderr
        return process, json.loads(evidence_path.read_text(encoding="utf-8"))["cases"]

    try:
        normal = [
            {"name": "GET all", "request": {"operationId": "listData"},
             "response_check": {"expect": {"status": 200}}, "db_response_check": mapping},
            {"name": "POST", "request": {"operationId": "createData", "body": {"name": "C", "location_id": "L3"}},
             "response_check": {"expect": {"status": 201}},
             "db_check": {"table": table, "where": {"name": "C"},
                          "expect": {"exists": True, "columns": {"name": "C", "location_id": "L3"}}}},
            {"name": "PUT", "request": {"operationId": "replaceData", "path_params": {"id": 1}, "body": {"name": "A2"}},
             "response_check": {"expect": {"status": 200}},
             "db_check": {"table": table, "where": {"id": 1}, "expect": {"columns": {"name": "A2"}}}},
            {"name": "PATCH", "request": {"operationId": "patchData", "path_params": {"id": 1},
                                            "body": {"location_id": "L9"}},
             "response_check": {"expect": {"status": 200}},
             "db_check": {"table": table, "where": {"id": 1}, "expect": {"columns": {"location_id": "L9"}}}},
            {"name": "DELETE", "request": {"operationId": "deleteData", "path_params": {"id": 2}},
             "response_check": {"expect": {"status": 200}},
             "db_check": {"table": table, "where": {"id": 2}, "expect": {"exists": False}}},
        ]
        result, cases = run(normal, "normal")
        assert result.returncode == 0, result.stdout + result.stderr
        assert [case["verdict"] for case in cases] == ["OK"] * 5
        assert cases[0]["db_response_comparison"]["expected_count"] == 2
        assert cases[0]["db_response_comparison"]["actual_count"] == 2
        assert cases[1]["db_check"]["matching_rows_before"] == 0
        assert cases[1]["db_check"]["matching_rows_after"] == 1

        wrong, cases = run([
            {"name": "wrong GET", "request": {"operationId": "wrongData"},
             "response_check": {"expect": {"status": 200}}, "db_response_check": mapping},
            {"name": "noop POST", "request": {"operationId": "noopData", "body": {"name": "A2"}},
             "response_check": {"expect": {"status": 201}},
             "db_check": {"table": table, "where": {"name": "A2"},
                          "expect": {"columns": {"name": "A2"}}}},
        ], "wrong")
        assert wrong.returncode == 1, wrong.stdout + wrong.stderr
        assert [case["verdict"] for case in cases] == ["NG", "NG"]
        assert "POST後に対象行が増えていません" in cases[1]["detail"]

        execute(f'TRUNCATE TABLE "{table}"')
        empty, cases = run([
            {"name": "empty GET", "request": {"operationId": "listData"},
             "response_check": {"expect": {"status": 400}}, "db_response_check": mapping},
        ], "empty")
        assert empty.returncode == 0, empty.stdout + empty.stderr
        assert cases[0]["verdict"] == "OK"
        assert cases[0]["db_response_comparison"]["expected_rows"] == []
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)
        execute(f'DROP TABLE "{table}"')
