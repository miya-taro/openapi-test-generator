#!/usr/bin/env python3
"""Run the complete local verification suite, including disposable API + PostgreSQL E2E tests.

Prerequisites are installed development dependencies, Node/npm, Rust/Cargo, Docker, and the
``postgres:16`` image (Docker pulls it if it is not cached). The database integration test starts
its own uniquely named PostgreSQL container and removes only that container when it finishes.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import socket
import subprocess
import sys
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


class VerificationError(RuntimeError):
    pass


def _run(label: str, command: list[str], *, cwd: Path = ROOT, env: dict | None = None) -> None:
    print(f"\n[verify] {label}", flush=True)
    print(f"[verify] $ {' '.join(command)}", flush=True)
    try:
        result = subprocess.run(command, cwd=cwd, env=env, check=False)
    except FileNotFoundError as error:
        raise VerificationError(f"必要なコマンドが見つかりません: {command[0]}") from error
    if result.returncode:
        raise VerificationError(f"{label} が終了コード {result.returncode} で失敗しました")


def _free_port() -> int:
    with socket.socket() as listener:
        listener.bind(("127.0.0.1", 0))
        return int(listener.getsockname()[1])


def _postgres_host_port(container_name: str) -> int:
    result = subprocess.run(
        ["docker", "port", container_name, "5432/tcp"],
        cwd=ROOT,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )
    match = re.search(r":(\d+)\s*$", result.stdout)
    if not match:
        raise VerificationError(f"PostgreSQLの公開ポートを取得できません: {result.stdout.strip()}")
    return int(match.group(1))


def _wait_for_postgres(port: int, timeout: float = 45.0) -> None:
    try:
        import psycopg2
    except ImportError as error:
        raise VerificationError("psycopg2がありません。requirements-runtime.txtをインストールしてください") from error

    deadline = time.monotonic() + timeout
    last_error: Exception | None = None
    while time.monotonic() < deadline:
        try:
            connection = psycopg2.connect(
                host="127.0.0.1",
                port=port,
                dbname="apitester_test",
                user="postgres",
                password="verify-local-only",
                connect_timeout=2,
            )
            connection.close()
            return
        except psycopg2.OperationalError as error:
            last_error = error
            time.sleep(0.5)
    raise VerificationError(f"PostgreSQLが起動しませんでした: {last_error}")


def _run_database_e2e(artifact_dir: Path) -> None:
    container_name = f"openapi-verify-{uuid.uuid4().hex[:12]}"
    password = "verify-local-only"
    config_path = artifact_dir / "db-config.json"
    port: int | None = None
    started = False
    try:
        _run(
            "使い捨てPostgreSQLを起動",
            [
                "docker", "run", "--detach", "--rm", "--name", container_name,
                "--label", "com.openapi-test-generator.verify=true",
                "--env", f"POSTGRES_PASSWORD={password}",
                "--env", "POSTGRES_DB=apitester_test",
                "--env", "POSTGRES_USER=postgres",
                "--publish", "127.0.0.1::5432",
                "postgres:16",
            ],
        )
        started = True
        port = _postgres_host_port(container_name)
        _wait_for_postgres(port)
        config_path.write_text(
            json.dumps({
                "postgres": {
                    "host": "127.0.0.1",
                    "port": port,
                    "dbname": "apitester_test",
                    "user": "postgres",
                    "password": password,
                },
            }, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )

        _run("DBシナリオ用スキーマを作成", [sys.executable, "docs/apply_schema.py", "--config", str(config_path)])
        api_env = os.environ.copy()
        api_env["OPENAPI_TEST_DB_CONFIG"] = str(config_path)
        _run(
            "HTTP + DB シナリオE2E (CRUD)",
            [
                sys.executable, "docs/run_e2e.py",
                "--config", str(config_path),
                "--output-dir", str(artifact_dir / "db-e2e"),
                "--reset-db-between-layers",
            ],
            env=api_env,
        )
    finally:
        if started:
            # The random name is generated by this process; never select or remove a pre-existing DB.
            subprocess.run(["docker", "rm", "--force", container_name], cwd=ROOT, check=False)


def _verify(artifact_dir: Path, include_e2e: bool, include_rust: bool) -> None:
    artifact_dir.mkdir(parents=True, exist_ok=True)
    python = sys.executable
    npm = "npm.cmd" if os.name == "nt" else "npm"
    cargo = "cargo.exe" if os.name == "nt" else "cargo"

    _run("runnerテストfixtureを生成", [python, "runner/tests/make_fixture.py"])
    for label, target in [
        ("Generator tests", "tests"),
        ("Runner tests", "runner/tests"),
        ("Workflow tests", "workflow/tests"),
        ("Shared GUI tests", "gui/tests"),
    ]:
        _run(label, [python, "-m", "pytest", target, "-q", "-p", "no:cacheprovider"])

    _run("Python lint", [python, "-m", "ruff", "check", "."])
    _run("GUI unit tests", [npm, "test"], cwd=ROOT / "gui-tauri")
    _run("GUI lint", [npm, "run", "lint"], cwd=ROOT / "gui-tauri")
    _run("GUI production build", [npm, "run", "build"], cwd=ROOT / "gui-tauri")
    if include_rust:
        _run("Tauri Rust tests", [cargo, "test", "--manifest-path", "src-tauri/Cargo.toml"], cwd=ROOT / "gui-tauri")
        _run(
            "Tauri Rust lint",
            [cargo, "clippy", "--manifest-path", "src-tauri/Cargo.toml", "--", "-D", "warnings"],
            cwd=ROOT / "gui-tauri",
        )
    else:
        print("\n[verify][SKIP] Tauri Rust tests and lint (--skip-tauri-rust)", flush=True)

    if include_e2e:
        _run(
            "OpenAPI contract E2E",
            [
                python, "docs/run_validation_e2e.py",
                "--output-dir", str(artifact_dir / "contract-e2e"),
            ],
        )
        _run_database_e2e(artifact_dir)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir",
        type=Path,
        help="保存する生成物の場所（省略時は .artifacts/verify-all/<日時>）",
    )
    parser.add_argument("--skip-e2e", action="store_true", help="HTTP/DBのE2Eを省略する")
    parser.add_argument("--skip-tauri-rust", action="store_true", help="Rust toolchainがない環境でRust確認を省略する")
    args = parser.parse_args()

    artifact_dir = args.output_dir or (
        ROOT / ".artifacts" / "verify-all" / datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    )
    artifact_dir = artifact_dir.resolve()
    try:
        _verify(
            artifact_dir,
            include_e2e=not args.skip_e2e,
            include_rust=not args.skip_tauri_rust,
        )
    except VerificationError as error:
        print(f"\n[verify][FAIL] {error}", file=sys.stderr)
        print(f"検証成果物: {artifact_dir}", file=sys.stderr)
        return 1

    print("\n[verify][OK] 指定された検証に成功しました")
    print(f"検証成果物: {artifact_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
